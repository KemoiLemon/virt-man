/// Git remote the generated install script clones when the daemon host has no
/// checkout yet. `dev` is the canonical development line.
const REPO_URL: &str = "ssh://git@git.kemoi.top:2222/kemoi/virt-man.git";

/// Bash script that installs virt-man-daemon on the hypervisor host with the
/// given token, so the token the web backend holds matches the daemon's.
///
/// Kept separate from `create` so it is unit-testable without a daemon.
fn install_script(token: &str) -> String {
    format!(
        r#"#!/usr/bin/env bash
# Generated by virt-man: installs virt-man-daemon with the token from the
# Add Server dialog. Run this on the daemon (hypervisor) host.
set -euo pipefail
export VIRT_MAN_TOKEN='{token}'

REPO="${{VIRT_MAN_REPO:-/opt/virt-man}}"
if [[ ! -d "$REPO/.git" ]]; then
  command -v git >/dev/null 2>&1 || {{ echo "git is required" >&2; exit 1; }}
  git clone {repo} "$REPO"
  git -C "$REPO" checkout dev
fi
cd "$REPO"
sudo ./daemon/install.sh
"#,
        token = token,
        repo = REPO_URL,
    )
}

pub fn routes(state: &AppState) -> Router<AppState> {
    let read = Router::new()
        .route("/connections", get(list))
        .route("/connections/{id}/test", get(test))
        // Each handler checks its own daemon: listing filters by it.
        .route("/connections/{id}/cert", get(fetch_cert));
    let write = Router::new()
        .route("/connections", axum::routing::post(create))
        .route(
            "/connections/{id}",
            axum::routing::put(update).delete(remove),
        )
        .layer(middleware::from_fn(auth::require_priv(
            state.clone(),
            "/",
            "Sys.Modify",
        )));
    Router::new()
        .merge(read)
        .merge(write)
        .layer(middleware::from_fn(auth::require_user(state.clone())))
}

fn conn_json(c: &Connection, health: Option<&crate::health::DaemonHealth>) -> Value {
    json!({
        // Unknown until the first probe (a few seconds after start): report
        // online rather than flash an offline banner for a healthy server.
        "online": health.is_none_or(|h| h.online),
        "offline_since_ms": health.filter(|h| !h.online).map(|h| h.since_ms),
        "offline_error": health.filter(|h| !h.online).and_then(|h| h.error.clone()),
        "id": c.id,
        "name": c.name,
        "url": c.url,
        "fingerprint": c.fingerprint,
        "has_token": !c.token.is_empty(),
        "has_cert": c.cert.is_some(),
    })
}

/// The daemons the caller may see: those they hold `Sys.Audit` on.
async fn list(
    State(state): State<AppState>,
    axum::extract::Extension(user): axum::extract::Extension<User>,
) -> Json<Value> {
    let health = state.health.read().expect("health lock poisoned").clone();
    let store = state.read();
    let conns: Vec<Value> = store
        .connections
        .iter()
        .filter(|c| store.can(&user, &crate::perm::node_path(&c.id), "Sys.Audit"))
        .map(|c| conn_json(c, health.get(&c.id)))
        .collect();
    Json(json!(conns))
}

#[derive(Deserialize)]
struct UpsertReq {
    name: String,
    url: String,
    #[serde(default)]
    token: String,
    /// PEM of the pinned cert, or "auto" to fetch it from the daemon.
    #[serde(default)]
    cert: Option<String>,
    #[serde(default)]
    generate_token: bool,
}

async fn create(
    State(state): State<AppState>,
    Json(req): Json<UpsertReq>,
) -> Result<Json<Value>, ApiError> {
    let name = req.name.trim().to_string();
    if name.is_empty() {
        return Err(ApiError::bad_request("name is required"));
    }
    let url = req.url.trim().to_string();
    daemon::parse_url(&url)?;

    // A blank token means "generate one": the daemon may not exist yet, in
    // which case the client gets an install script carrying this exact token.
    let generated = req.generate_token || req.token.trim().is_empty();
    let token = if generated {
        format!("vm_{}", random_hex(24))
    } else {
        req.token.trim().to_string()
    };

    let (cert, fingerprint, unreachable) = match req.cert.as_deref() {
        Some("auto") | None if url.starts_with("https://") => {
            match daemon::fetch_cert(&url).await {
                Ok((pem, fp)) => (Some(pem), Some(fp), false),
                // Fresh setup: the daemon is not installed yet. Rather than
                // fail the save, keep the connection (no cert pinned yet) and
                // hand back an install script for the daemon host. The client
                // re-fetches the cert every second until it lands.
                Err(_) if generated => (None, None, true),
                Err(e) => {
                    return Err(ApiError::bad_request(format!(
                        "certificate fetch failed: {e}"
                    )))
                }
            }
        }
        Some(pem) if !pem.is_empty() => {
            let fp = daemon::fingerprint_of_pem(pem)
                .map_err(|e| ApiError::bad_request(format!("invalid certificate: {e}")))?;
            (Some(pem.to_string()), Some(fp), false)
        }
        _ => (None, None, false),
    };

    let mut store = state.write();
    let conn = Connection {
        id: random_hex(8),
        name,
        url,
        token,
        cert,
        fingerprint,
    };
    store.connections.push(conn.clone());
    store.save(&state.data_dir)?;
    drop(store);

    let mut out = conn_json(&conn, None);
    if unreachable {
        out["daemon_unreachable"] = json!(true);
        out["install_script"] = json!(install_script(&conn.token));
    }
    Ok(Json(out))
}

async fn update(
    State(state): State<AppState>,
    Path(id): Path<String>,
    Json(req): Json<UpsertReq>,
) -> Result<Json<Value>, ApiError> {
    let url = req.url.trim().to_string();
    daemon::parse_url(&url)?;

    let mut store = state.write();
    let Some(conn) = store.connections.iter_mut().find(|c| c.id == id) else {
        return Err(ApiError::not_found("no such connection"));
    };
    conn.name = if req.name.trim().is_empty() {
        conn.name.clone()
    } else {
        req.name.trim().into()
    };
    conn.url = url;
    if req.generate_token {
        conn.token = format!("vm_{}", random_hex(24));
    } else if !req.token.trim().is_empty() {
        conn.token = req.token.trim().to_string();
    }
    // Re-pin cert if explicitly provided, otherwise keep existing pin for a
    // URL change the user has already confirmed.
    if let Some(pem) = req.cert.as_deref().filter(|p| !p.is_empty()) {
        conn.cert = Some(pem.to_string());
        conn.fingerprint = daemon::fingerprint_of_pem(pem).ok();
    }
    let conn = conn.clone();
    store.save(&state.data_dir)?;
    Ok(Json(conn_json(&conn, None)))
}

async fn remove(
    State(state): State<AppState>,
    Path(id): Path<String>,
) -> Result<Json<Value>, ApiError> {
    {
        let mut store = state.write();
        let Some(pos) = store.connections.iter().position(|c| c.id == id) else {
            return Err(ApiError::not_found("no such connection"));
        };
        store.connections.remove(pos);
        store.resources.retain(|r| r.conn != id);
        let node = crate::perm::node_path(&id);
        store
            .acl
            .retain(|e| e.path != node && !e.path.starts_with(&format!("{node}/")));
        for u in &mut store.users {
            u.quota.daemons.remove(&id);
        }
        store.save(&state.data_dir)?;
    }
    // A removed server takes its graphs with it. The collector would also do
    // this on its next tick; doing it here means the answer is already true.
    let live: Vec<String> = state
        .read()
        .connections
        .iter()
        .map(|c| c.id.clone())
        .collect();
    let history = state.history.clone();
    let access = state.access.clone();
    tokio::task::spawn_blocking(move || -> Result<(), String> {
        history.keep_only(&live)?;
        access.keep_only(&live)?;
        Ok(())
    })
    .await
    .map_err(|e| ApiError::internal(e.to_string()))??;
    Ok(Json(json!({"deleted": id})))
}

/// Fetch and return the daemon's certificate + fingerprint so the client can
/// confirm before pinning. Does not modify the stored connection.
async fn fetch_cert(
    State(state): State<AppState>,
    Path(id): Path<String>,
    axum::extract::Extension(user): axum::extract::Extension<User>,
) -> Result<Json<Value>, ApiError> {
    super::enforce(&state, &user, "/", "Sys.Modify")?;
    let url = {
        let store = state.read();
        let Some(c) = store.connection(&id) else {
            return Err(ApiError::not_found("no such connection"));
        };
        c.url.clone()
    };
    let (pem, fp) = daemon::fetch_cert(&url)
        .await
        .map_err(|e| ApiError::bad_request(format!("certificate fetch failed: {e}")))?;
    Ok(Json(json!({"cert": pem, "fingerprint": fp})))
}

/// Test a connection by hitting the daemon's /health through the pinned client.
async fn test(
    State(state): State<AppState>,
    Path(id): Path<String>,
    axum::extract::Extension(user): axum::extract::Extension<User>,
) -> Result<Json<Value>, ApiError> {
    super::enforce(&state, &user, &crate::perm::node_path(&id), "Sys.Audit")?;
    let conn = {
        let store = state.read();
        store.connection(&id).cloned()
    }
    .ok_or_else(|| ApiError::not_found("no such connection"))?;

    let client = daemon::http_client(&conn)
        .map_err(|e| ApiError::bad_request(format!("connection error: {e}")))?;
    let resp = client
        .get(format!("{}/health", conn.url.trim_end_matches('/')))
        .header("Authorization", format!("Bearer {}", conn.token))
        .send()
        .await
        .map_err(|e| ApiError::bad_request(format!("daemon unreachable: {e}")))?;
    let status = resp.status();
    let body = resp.text().await.unwrap_or_default();
    Ok(Json(json!({
        "ok": status.is_success(),
        "status": status.as_u16(),
        "body": body,
    })))
}

#[cfg(test)]
mod tests {
    use super::install_script;

    #[test]
    fn install_script_carries_the_token_into_the_installer() {
        let s = install_script("vm_abc123");
        assert!(s.starts_with("#!/usr/bin/env bash"), "executable: {s}");
        assert!(
            s.contains("VIRT_MAN_TOKEN='vm_abc123'"),
            "token embedded: {s}"
        );
        assert!(
            s.contains("sudo ./daemon/install.sh"),
            "runs the real installer: {s}"
        );
    }
}
